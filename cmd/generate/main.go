var (
	fpath          = "."
	jonsonPath     = "github.com/doejon/jonson"
	apiNameMatcher = regexp.MustCompile(`^(.+)V([0-9]+)$`)
	apiTypeMatcher = regexp.MustCompile(`(^|\n)@generate($|\n)`)
)

func init() {
	flag.StringVar(&fpath, "path", fpath, "filepath to scan")
	flag.StringVar(&jonsonPath, "jonson", jonsonPath, "path to jonson library")
}

// file storing internal api calls
const fNameProcedure = "jonson.procedure-calls.gen.go"

// file storing provider types
const fNameProvider = "jonson.providers.gen.go"

// file storing field descriptions taken from struct field comments
const fNameDescriptions = "jonson.descriptions.gen.go"

// some file names need to be ignored
var ignoredFileNames = map[string]struct{}{
	fNameProcedure:    {},
	fNameProvider:     {},
	fNameDescriptions: {},
}

// readPackage parses the go files in fpath, ignoring tests and the generated files.
// All files need to belong to the same package.
func readPackage() (string, []*ast.File, *token.FileSet, error) {
	entries, err := os.ReadDir(fpath)
	if err != nil {
		return "", nil, nil, err
	}

	fset := token.NewFileSet()
	var (
		pkgName string
		files   []*ast.File
	)
	// os.ReadDir sorts by name, so files and their positions are in a stable order
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || strings.HasSuffix(e.Name(), "_test.go") {
			continue
		}
		if _, ok := ignoredFileNames[e.Name()]; ok {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(fpath, e.Name()), nil, parser.ParseComments)
		if err != nil {
			return "", nil, nil, err
		}
		if pkgName != "" && f.Name.Name != pkgName {
			return "", nil, nil, fmt.Errorf("exactly 1 package expected, got: %s and %s in path %s", pkgName, f.Name.Name, fpath)
		}
		pkgName = f.Name.Name
		files = append(files, f)
	}
	if len(files) == 0 {
		return "", nil, nil, fmt.Errorf("no go files found in path %s", fpath)
	}
	return pkgName, files, fset, nil
}

func writeFile(name string, content []byte) error {
	formatted, err := format.Source(content)
	if err != nil {
		return fmt.Errorf("format %s: %w", name, err)
	}
	outputFilename := filepath.Join(fpath, name)
	return os.WriteFile(outputFilename, formatted, 0644)
}

func prependHeader(wtr *bytes.Buffer, pkgName string, imports ...string) []byte {
	for i, v := range imports {
		imports[i] = "\"" + v + "\""
	}
	// file header
	fileContent := wtr.String()
	wtr.Reset()

	importBlock := ""
	if len(imports) > 0 {
		importBlock = "import (\n\t" + strings.Join(imports, "\n\t") + "\n)\n"
	}

	fileContent = `// Code generated by jonson-generate; DO NOT EDIT.

package ` + pkgName + `

` + importBlock + fileContent
	return []byte(fileContent)
}

// writeProcedureFile writes the procedure file
func writeProcedureFile(fset *token.FileSet, pkgName string, listMethods []*ast.FuncDecl, types map[string]*ast.TypeSpec) error {
	wtr := bytes.NewBuffer([]byte{})

	needsJonsonImport := false

	extractParam := func(lastArg *ast.Field, decl *ast.TypeSpec, ident *ast.Ident, stru *ast.StructType) string {
		lastArgName := ""
		if len(lastArg.Names) > 0 {
			lastArgName = lastArg.Names[0].Name
		}

		// in case the last param is called 'params', we enforce the use of params
		// otherwise the last argument could also be something else than a param.
		expectParam := lastArgName == "params"

		var err error
		if stru.Fields == nil || len(stru.Fields.List) <= 0 {
			err = fmt.Errorf("missing jonson.Params field in struct %s", decl.Name.String())
		} else if p, ok := stru.Fields.List[0].Type.(*ast.SelectorExpr); ok {
			if p.X.(*ast.Ident).Name == "jonson" && p.Sel.Name == "Params" {
				return ident.Name
			}
		} else {
			err = fmt.Errorf("jonson.Params field in struct %s, should be first field", decl.Name.String())
		}
		if err != nil && expectParam {
			panic(err)
		}
		return ""
	}

	// walk methods
	for _, object := range listMethods {
		pos := fset.Position(object.Pos())

		if object.Recv == nil {
			continue
		}
		if len(object.Recv.List) <= 0 {
			continue
		}

		objStarExp, ok := object.Recv.List[0].Type.(*ast.StarExpr)
		if !ok {
			continue
		}
		objIdent, ok := objStarExp.X.(*ast.Ident)
		if !ok {
			continue
		}

		// only take those into account that equal package name
		if firstToLower(objIdent.Name) != pkgName {
			continue
		}
		systemName := jonson.ToKebabCase(objIdent.Name)

		// input
		var paramType string

		// by default, all rpc calls use post.
		// However, in case the developer wants to force certain http methods,
		// we will find them in the function signature.
		rpcHttpMethod := getRpcHttpMethod(object)

		if len(object.Type.Params.List) > 0 {
			lastArg := object.Type.Params.List[len(object.Type.Params.List)-1]
			starExpr, ok := lastArg.Type.(*ast.StarExpr)
			if ok {
				if ident, ok := starExpr.X.(*ast.Ident); ok {
					if decl, ok := types[ident.Name]; ok {
						if stru, ok := decl.Type.(*ast.StructType); ok {
							paramType = extractParam(lastArg, decl, ident, stru)
						}
					}
				}
			}
		}

		var params, parArg string
		if paramType != "" {
			params = ", p *" + paramType
			parArg = "p"
		} else {
			parArg = "nil"
		}

		// output
		var resultType string
		if l := len(object.Type.Results.List); l == 2 {
			resultType = object.Type.Results.List[0].Type.(*ast.StarExpr).X.(*ast.Ident).Name
		} else if l != 1 {
			panic(errors.New("unexpected results count"))
		}

		var result, vAssign, errRet, valRet, nilRet string
		if resultType != "" {
			result = "(*" + resultType + ", error)"
			vAssign = "v, err"
			errRet = "nil, err"
			valRet = `if v != nil {
		return v.(*` + resultType + `), nil
	}`
			nilRet = "nil, nil"
		} else {
			result = "error"
			vAssign = "_, err"
			errRet = "err"
			nilRet = "nil"
		}

		// comment line
		needsJonsonImport = true
		method, version := jonson.SplitGoMethodName(object.Name.Name)
		methodName := jonson.GetDefaultMethodName(systemName, method, version)
		fmt.Fprintf(
			wtr,
			`
// %s -- %s
func %s(ctx *jonson.Context%s) %s {
	%s := ctx.CallMethod("%s", %s, %s)
	if err != nil {
		return %s
	}
	%s
	return %s
}
`,
			pos.Filename, object.Name,
			object.Name, params, result,
			vAssign, methodName, rpcHttpMethod, parArg,
			errRet,
			valRet,
			nilRet,
		)
	}

	imports := []string{}
	if needsJonsonImport {
		imports = append(imports, jonsonPath)
	}

	fContent := prependHeader(wtr, pkgName, imports...)

	return writeFile(fNameProcedure, fContent)
}

func firstToLower(s string) string {

	if len(s) == 0 {
		return s
	}

	r := []rune(s)
	r[0] = unicode.ToLower(r[0])

	return string(r)
}

func writeTypesFile(fset *token.FileSet, pkgName string, listTypes []*ast.TypeSpec) error {
	needsJonsonImport := false
	wtr := bytes.NewBuffer([]byte{})

	// walk types
	for _, object := range listTypes {
		pos := fset.Position(object.Pos())
		name := object.Name.Name

		var ts, typeName string
		if _, ok := object.Type.(*ast.InterfaceType); ok {
			ts = "interface" + name
			typeName = name
		} else if _, ok := object.Type.(*ast.StructType); ok {
			ts = "struct"
			typeName = "*" + name
		} else {
			continue
		}

		needsJonsonImport = true
		fmt.Fprintf(
			wtr,
			`
// %s:%d -- %s -- %s
var Type%s = reflect.TypeFor[*%s]()

func Require%s(ctx *jonson.Context) %s {
	if v := ctx.Require(Type%s).(%s); v != nil {
		return v
	}
	return nil
}
`,
			pos.Filename, pos.Line,
			name,
			ts,
			name,
			typeName,
			name,
			typeName,
			name,
			typeName,
		)
	}

	imports := []string{}
	if len(listTypes) > 0 {
		imports = append(imports, "reflect")
	}
	if needsJonsonImport {
		imports = append(imports, "github.com/doejon/jonson")
	}

	fContent := prependHeader(wtr, pkgName, imports...)

	return writeFile(fNameProvider, fContent)
}

func main() {
	flag.Parse()
	pkgName, files, fset, err := readPackage()
	if err != nil {
		log.Fatalf("error: %s", err)
	}

	dc, err := doc.NewFromFiles(fset, files, fpath, doc.PreserveAST)
	if err != nil {
		log.Fatalf("error: %s", err)
	}

	var (
		whitelistTypes []string
		listTypes      []*ast.TypeSpec
		listMethods    []*ast.FuncDecl
		types          = map[string]*ast.TypeSpec{}
	)

	for _, t := range dc.Types {
		if apiTypeMatcher.MatchString(t.Doc) {
			whitelistTypes = append(whitelistTypes, t.Name)
		}
	}

	for _, f := range files {
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				// methods
				if apiNameMatcher.MatchString(d.Name.Name) {
					listMethods = append(listMethods, d)
				}
			case *ast.GenDecl:
				// types
				if d.Tok != token.TYPE {
					continue
				}
				for _, spec := range d.Specs {
					ts := spec.(*ast.TypeSpec)
					types[ts.Name.Name] = ts
					if ts.Name.IsExported() && slices.Contains(whitelistTypes, ts.Name.Name) {
						listTypes = append(listTypes, ts)
					}
				}
			}
		}
	}

	// sort by position asc
	sort.Slice(listTypes, func(i, j int) bool { return listTypes[i].Pos() < listTypes[j].Pos() })
	sort.Slice(listMethods, func(i, j int) bool { return listMethods[i].Pos() < listMethods[j].Pos() })

	if err := writeProcedureFile(fset, pkgName, listMethods, types); err != nil {
		log.Fatalf("error: %s", err)
	}

	if err := writeTypesFile(fset, pkgName, listTypes); err != nil {
		log.Fatalf("error: %s", err)
	}

	if err := writeDescriptionsFile(pkgName, files, listMethods); err != nil {
		log.Fatalf("error: %s", err)
	}
}

func getRpcHttpMethod(decl *ast.FuncDecl) string {
	var m string = "jonson.RpcHttpMethodPost"
	for _, v := range decl.Type.Params.List {
		intf, ok := v.Type.(*ast.SelectorExpr)
		if !ok {
			continue
		}
		switch intf.Sel.Name {
		case "HttpGet":
			return "jonson.RpcHttpMethodGet"
		case "HttpPost":
			return "jonson.RpcHttpMethodPost"
		}

	}

	return m
}

// writeDescriptionsFile writes the field and method descriptions file
func writeDescriptionsFile(pkgName string, files []*ast.File, listMethods []*ast.FuncDecl) error {
	wtr := bytes.NewBuffer([]byte{})
	for _, f := range files {
		writeFieldDescriptions(wtr, f)
	}
	writeMethodDescriptions(wtr, pkgName, listMethods)
	return writeFile(fNameDescriptions, prependHeader(wtr, pkgName))
}

// writeMethodDescriptions writes a JonsonMethodDescriptions method on the package's
// system type, mapping each documented remote procedure to its doc comment, e.g. as
// the description of an MCP tool. Systems are found like in writeProcedureFile.
func writeMethodDescriptions(wtr *bytes.Buffer, pkgName string, listMethods []*ast.FuncDecl) {
	var recv string
	var entries []string
	for _, fn := range listMethods {
		if fn.Recv == nil || len(fn.Recv.List) == 0 {
			continue
		}
		star, ok := fn.Recv.List[0].Type.(*ast.StarExpr)
		if !ok {
			continue
		}
		ident, ok := star.X.(*ast.Ident)
		if !ok || firstToLower(ident.Name) != pkgName {
			continue
		}
		text := strings.TrimSpace(fn.Doc.Text())
		if text == "" {
			continue
		}
		recv = ident.Name
		method, version := jonson.SplitGoMethodName(fn.Name.Name)
		name := jonson.GetDefaultMethodName(jonson.ToKebabCase(ident.Name), method, version)
		entries = append(entries, "\t\t"+strconv.Quote(name)+": "+strconv.Quote(text)+",\n")
	}
	if len(entries) == 0 {
		return
	}
	fmt.Fprintf(wtr, "\nfunc (*%s) JonsonMethodDescriptions() map[string]string {\n\treturn map[string]string{\n%s\t}\n}\n",
		recv, strings.Join(entries, ""))
}

// writeFieldDescriptions writes a JonsonFieldDescriptions method for each exported,
// non-generic struct of f that has at least one commented field. The comment of a field
// (doc comment above, or line comment behind it) becomes its description, e.g. in the
// MCP tool's input schema.
func writeFieldDescriptions(wtr *bytes.Buffer, f *ast.File) {
	for _, d := range f.Decls {
		gen, ok := d.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE {
			continue
		}
		for _, spec := range gen.Specs {
			ts := spec.(*ast.TypeSpec)
			st, ok := ts.Type.(*ast.StructType)
			if !ok || !ts.Name.IsExported() || ts.TypeParams != nil {
				continue
			}
			var entries []string
			for _, field := range st.Fields.List {
				text := field.Doc.Text()
				if text == "" {
					text = field.Comment.Text()
				}
				text = strings.Join(strings.Fields(text), " ")
				if text == "" {
					continue
				}
				for _, name := range field.Names {
					if name.IsExported() {
						entries = append(entries, "\t\t"+strconv.Quote(name.Name)+": "+strconv.Quote(text)+",\n")
					}
				}
			}
			if len(entries) == 0 {
				continue
			}
			fmt.Fprintf(wtr, "\nfunc (*%s) JonsonFieldDescriptions() map[string]string {\n\treturn map[string]string{\n%s\t}\n}\n",
				ts.Name.Name, strings.Join(entries, ""))
		}
	}
}
